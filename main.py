def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="ruijie-collector",
        description=(
            "Batch-collect running-configs from Ruijie switches "
            "via the built-in web management API."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python main.py                        # use config.yml in current directory
  python main.py -c /etc/switches.yml   # custom config path
  python main.py -o /data/backups       # custom output directory
  python main.py --dry-run              # list targets without connecting
  python main.py -v                     # verbose / debug output
  python main.py --decode-token TOKEN   # decode a Ruijie auth token
        """,
    )
    p.add_argument(
        "-c", "--config",
        default="config.yml",
        metavar="FILE",
        help="Path to YAML configuration file (default: config.yml)",
    )
    p.add_argument(
        "-o", "--output",
        default=".",
        metavar="DIR",
        help="Output directory (default: current directory)",
    )
    p.add_argument(
        "-v", "--verbose",
        action="store_true",
        help="Enable DEBUG-level logging",
    )
    p.add_argument(
        "--dry-run",
        action="store_true",
        help="Print target IPs and exit without connecting",
    )
    p.add_argument(
        "--decode-token",
        metavar="TOKEN",
        help="Decode a Ruijie auth token and print the plaintext credentials",
    )
    return p


def main() -> None:
    args = build_parser().parse_args()

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    # ── Utility: decode a token ──────────────────────────────────────────
    if args.decode_token:
        creds = decode_auth_token(args.decode_token)
        if creds:
            print(f"Username : {creds[0]}")
            print(f"Password : {creds[1]}")
        else:
            print("Could not decode token (prefix mismatch or corrupted data).")
        return

    # ── Load config ───────────────────────────────────────────────────────
    cfg         = load_config(args.config)
    auth_token  = resolve_auth_token(cfg.get("auth", {}))
    targets_cfg = cfg.get("targets", {})
    request_cfg = cfg.get("request", {})

    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)

    ips = expand_targets(targets_cfg)
    if not ips:
        logger.error(
            "No valid target IPs found. "
            "Check the 'targets' section in config.yml."
        )
        sys.exit(1)

    logger.info("Targets: %d IP(s)", len(ips))

    if args.dry_run:
        print(f"\nDry-run — {len(ips)} target(s):")
        for ip in ips:
            print(f"  {ip}")
        print()
        return

    # ── Shared state for maps.json ────────────────────────────────────────
    maps_path = output_dir / "maps.json"
    maps_lock = threading.Lock()

    # ── Concurrent collection ─────────────────────────────────────────────
    max_workers = int(request_cfg.get("concurrent", 5))
    results: list[dict] = []

    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        future_map = {
            pool.submit(
                process_switch,
                ip,
                auth_token,
                request_cfg,
                output_dir,
                maps_path,
                maps_lock,
            ): ip
            for ip in ips
        }
        for future in as_completed(future_map):
            ip = future_map[future]
            try:
                results.append(future.result())
            except Exception as exc:  # noqa: BLE001
                logger.error("[%s] Unhandled exception: %s", ip, exc)
                results.append({"ip": ip, "success": False, "error": str(exc)})

    # ── Summary ───────────────────────────────────────────────────────────
    ok   = [r for r in results if r["success"]]
    fail = [r for r in results if not r["success"]]

    bar = "=" * 60
    print(f"\n{bar}")
    print("  Collection Summary")
    print(bar)
    print(f"  Total     : {len(results)}")
    print(f"  Success   : {len(ok)}")
    print(f"  Failed    : {len(fail)}")

    if ok:
        print(f"\n  {'IP Address':<22}  Hostname")
        print(f"  {'-'*22}  {'-'*20}")
        for r in sorted(ok, key=lambda x: ipaddress.ip_address(x["ip"])):
            print(f"  {r['ip']:<22}  {r['hostname']}")

    if fail:
        print(f"\n  {'IP Address':<22}  Error")
        print(f"  {'-'*22}  {'-'*30}")
        for r in sorted(fail, key=lambda x: x["ip"]):
            print(f"  {r['ip']:<22}  {r.get('error', 'unknown')}")

    if ok:
        print(f"\n  Mapping file : {maps_path}")
        print(f"  Configs dir  : {output_dir / 'configs'}")

    print(f"{bar}\n")


if __name__ == "__main__":
    main()
